r"""
stageA_stoi.py -- STOI / eSTOI of the audio generated by HiFi-GAN from the PREDICTED mel of the Stage-A models, on the TEST frames only.

Definition (as in ConvED-SR): SpeechBrain HiFi-GAN (speechbrain/tts-hifigan-ljspeech, the same vocoder as the ceiling check), generated audio
vs the ORIGINAL audio (22,050 Hz), pystoi with extended=False (STOI) and, for reference, extended=True (eSTOI).
Per participant: every contiguous run of predicted test frames (= one test block, the windows of a block joined) is synthesised and scored
against the original audio of the same frames; the participant's value = mean over those runs; reported = mean over participants.

Systems compared on exactly the same test frames:
  truth        HiFi-GAN of the TRUE mel (ceiling: what any prediction can reach)
  template     HiFi-GAN of the time-in-trial template (no neural input)  -> the floor to beat
  linear / baseline / hybrid / neuroincept / convedsr   predictions of the first finished seed of each model (default seed 42)
  *_null       (optional) the noise-input control
Listening: the first test block of every participant is also saved as a wav in  <OUT>\stageA_audio\  (original, truth, template, models).

Usage (SEEG_OUT_DIR set; speechbrain, torch, pystoi installed; runs on CPU):
    python stageA_stoi.py quick                 # sub-03 and sub-06, systems: truth, template, hybrid (a few minutes)
    python stageA_stoi.py                       # all participants, all systems (long on CPU; resumable: finished items are skipped)
    python stageA_stoi.py sub-03 sub-06         # chosen participants, all systems
    python stageA_stoi.py summary
Results: <OUT>\stageA_stoi\stoi_results.json   (one entry per participant and system)
"""
import os, sys, glob, json, time
import numpy as np
from scipy.io import wavfile

OUT = os.environ["SEEG_OUT_DIR"]
SR, HOP = 22050, 256
RES = os.path.join(OUT, "stageA_stoi"); os.makedirs(RES, exist_ok=True)
AUD = os.path.join(OUT, "stageA_audio"); os.makedirs(AUD, exist_ok=True)
JS = os.path.join(RES, "stoi_results.json")
ALL_SUBS = [f"sub-{i:02d}" for i in range(1, 11)]
SYSTEMS = ["truth", "template", "linear", "baseline", "hybrid", "neuroincept", "convedsr"]


def read_wav(path):
    sr, x = wavfile.read(path)
    x = x.astype(np.float64) / np.iinfo(x.dtype).max if x.dtype.kind == "i" else x.astype(np.float64)
    return sr, (x.mean(1) if x.ndim > 1 else x)


def runs_of(idx):
    """split the concatenated test-frame indices into contiguous runs -> list of (start_in_array, end_in_array)"""
    cut = np.where(np.diff(idx) != 1)[0] + 1
    b = np.concatenate([[0], cut, [len(idx)]])
    return list(zip(b[:-1], b[1:]))


def pred_file(system):
    f = sorted(glob.glob(os.path.join(OUT, "stageA", f"{system}_lr*_seed42_preds.npz"))) + \
        sorted(glob.glob(os.path.join(OUT, "stageA", f"{system}_seedNA_preds.npz")))       # linear has no lr / seed
    return f[0] if f else None


def any_pred_file():
    """truth and template do not depend on a model: take the test frames (and the saved template) from any finished model"""
    for m in ("hybrid", "baseline", "linear", "neuroincept", "convedsr"):
        f = pred_file(m)
        if f: return f
    return None


def get_vocoder():
    import torch
    from speechbrain.inference.vocoders import HIFIGAN
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    kw = {}
    try:
        from speechbrain.utils.fetching import LocalStrategy
        kw["local_strategy"] = LocalStrategy.COPY
    except Exception:
        pass
    hifi = HIFIGAN.from_hparams(source="speechbrain/tts-hifigan-ljspeech", savedir=os.path.join(OUT, "hifigan_ckpt"), run_opts={"device": dev}, **kw)

    def decode(mel_t80):                                  # (T, 80) raw log-mel -> waveform
        with torch.no_grad():
            m = torch.tensor(mel_t80.T, dtype=torch.float32)[None].to(dev)
            return hifi.decode_batch(m).squeeze().cpu().numpy()
    return decode


def score(subs, systems, decode, results, save):
    from pystoi import stoi
    for sub in subs:
        spec = np.load(os.path.join(OUT, f"{sub}_spec.npy"))
        sr, x = read_wav(glob.glob(os.path.join(OUT, f"{sub}_audio_*.wav"))[0]); assert sr == SR
        for sysname in systems:
            key = f"{sub}|{sysname}"
            if key in results:
                continue
            src = sysname
            f = any_pred_file() if sysname in ("truth", "template") else pred_file(sysname)
            if f is None:
                print(f"  {key}: no saved predictions for '{src}' yet - skipped"); continue
            z = np.load(f)
            if sub + "_idx" not in z.files:
                continue
            idx = z[sub + "_idx"]
            if sysname == "truth":
                mel = spec[idx]
            elif sysname == "template":
                mel = z[sub + "_T"]
            else:
                mel = z[sub + "_P"]
            t0 = time.time(); vals, evals = [], []
            for k, (a, b) in enumerate(runs_of(idx)):
                fr0, fr1 = int(idx[a]), int(idx[b - 1]) + 1
                y = decode(mel[a:b]); ref = x[fr0 * HOP: fr1 * HOP]; n = min(len(ref), len(y))
                vals.append(stoi(ref[:n], y[:n], SR, extended=False)); evals.append(stoi(ref[:n], y[:n], SR, extended=True))
                if k == 0:                                 # listening files: first test block
                    if sysname == "truth":
                        wavfile.write(os.path.join(AUD, f"{sub}_original.wav"), SR, (ref[:n] / (np.abs(ref[:n]).max() + 1e-9) * 0.9 * 32767).astype(np.int16))
                    yy = y[:n]; wavfile.write(os.path.join(AUD, f"{sub}_{sysname}.wav"), SR, (yy / (np.abs(yy).max() + 1e-9) * 0.9 * 32767).astype(np.int16))
            results[key] = dict(subject=sub, system=sysname, stoi=float(np.mean(vals)), estoi=float(np.mean(evals)), segments=len(vals), pred_file=os.path.basename(f))
            save(results)
            print(f"  {key}: STOI {np.mean(vals):.3f} | eSTOI {np.mean(evals):.3f} | {len(vals)} test blocks | {time.time() - t0:.0f}s", flush=True)


def summary(results=None):
    import pandas as pd
    r = results if results is not None else (json.load(open(JS)) if os.path.exists(JS) else {})
    if not r:
        print("no results yet"); return
    df = pd.DataFrame(r.values())
    pd.set_option("display.width", 200)
    print("STOI per participant (mean over test blocks):"); print(df.pivot(index="subject", columns="system", values="stoi").round(3).to_string())
    print("\nmean over participants:"); print(df.groupby("system")[["stoi", "estoi"]].mean().round(3).to_string())


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["summary"]:
        summary(); sys.exit()
    results = json.load(open(JS)) if os.path.exists(JS) else {}
    save = lambda r: json.dump(r, open(JS, "w"), indent=1)
    quick = args[:1] == ["quick"]
    subs = ["sub-03", "sub-06"] if quick else ([a for a in args if a.startswith("sub-")] or ALL_SUBS)
    systems = ["truth", "template", "hybrid"] if quick else SYSTEMS
    score(subs, systems, get_vocoder(), results, save)
    summary(results)
